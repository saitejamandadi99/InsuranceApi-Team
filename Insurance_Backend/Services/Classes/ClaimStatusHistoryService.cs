using System.Security.Claims;
using Insurance_Backend.DTO.RequestDTO;
using Insurance_Backend.DTO.ResponseDTO;
using Insurance_Backend.Exceptions;
using Insurance_Backend.Models;
using Insurance_Backend.Repositories.Interfaces;
using Insurance_Backend.Services.Interfaces;
using Microsoft.AspNetCore.Http;

namespace Insurance_Backend.Services.Classes
{
    public class ClaimStatusHistoryService : IClaimStatusHistoryService
    {
        private readonly IClaimStatusHistoryRepository _repository;

        public ClaimStatusHistoryService(
            IClaimStatusHistoryRepository repository)
        {
            _repository = repository;
        }

        // Add claim status history
        public async Task<ClaimStatusHistoryResponseDTO> AddClaimStatusHistory(
            ClaimStatusHistory history,
            ClaimsPrincipal user)
        {
            if (history == null)
            {
                throw new BusinessException(
                    "Claim status history data is required.",
                    StatusCodes.Status400BadRequest);
            }

            int userId = GetLoggedInUserId(user);

            // Record who performed the status change.
            history.UpdatedBy = userId;

            // The timestamp is generated by the server.
            history.UpdatedDate = DateTime.UtcNow;

            return await _repository.AddClaimStatusHistory(history);
        }

        // Get history by HistoryId
        public async Task<ClaimStatusHistoryResponseDTO?>
            GetClaimStatusHistoryById(int id)
        {
            ValidateId(id, "History ID");

            return await _repository.GetClaimStatusHistoryById(id);
        }

        // Get all history records
        public async Task<PaginatedResponseDTO<ClaimStatusHistoryResponseDTO>>
            GetAllClaimStatusHistories(PaginationQueryDTO query)
        {
            if (query == null)
            {
                throw new BusinessException(
                    "Pagination query is required.",
                    StatusCodes.Status400BadRequest);
            }

            return await _repository.GetAllClaimStatusHistories(query);
        }

        // Get history by ClaimId
        public async Task<PaginatedResponseDTO<ClaimStatusHistoryResponseDTO>>
            GetClaimStatusHistoryByClaimId(
                int claimId,
                PaginationQueryDTO query)
        {
            ValidateId(claimId, "Claim ID");

            if (query == null)
            {
                throw new BusinessException(
                    "Pagination query is required.",
                    StatusCodes.Status400BadRequest);
            }

            return await _repository.GetClaimStatusHistoryByClaimId(
                claimId,
                query);
        }

        // Get history by UpdatedBy user ID
        public async Task<PaginatedResponseDTO<ClaimStatusHistoryResponseDTO>>
            GetClaimStatusHistoryByUserId(
                int userId,
                PaginationQueryDTO query)
        {
            ValidateId(userId, "User ID");

            if (query == null)
            {
                throw new BusinessException(
                    "Pagination query is required.",
                    StatusCodes.Status400BadRequest);
            }

            return await _repository.GetClaimStatusHistoryByUserId(
                userId,
                query);
        }

        // Check whether history exists
        public async Task<bool> ClaimStatusHistoryExists(int id)
        {
            ValidateId(id, "History ID");

            return await _repository.ClaimStatusHistoryExists(id);
        }

        // Get authenticated user's ID
        private static int GetLoggedInUserId(ClaimsPrincipal user)
        {
            var userIdValue =
                user.FindFirst(ClaimTypes.NameIdentifier)?.Value
                ?? user.FindFirst("sub")?.Value
                ?? user.FindFirst("UserId")?.Value;

            if (!int.TryParse(userIdValue, out int userId) || userId <= 0)
            {
                throw new BusinessException(
                    "A valid authenticated user ID was not found.",
                    StatusCodes.Status401Unauthorized);
            }

            return userId;
        }

        // Validate IDs
        private static void ValidateId(int id, string fieldName)
        {
            if (id <= 0)
            {
                throw new BusinessException(
                    $"{fieldName} must be greater than zero.",
                    StatusCodes.Status400BadRequest);
            }
        }
    }
}